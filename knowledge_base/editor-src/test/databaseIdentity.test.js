import assert from 'node:assert/strict';
import { webcrypto } from 'node:crypto';
import { BlockNoteEditor } from '@blocknote/core';
import { schema } from '../src/schema.js';
import { mdToBlocks, blocksToMd } from '../src/markdown.js';
import { newDatabaseData, duplicateIdentityRepairs, editorDatabaseContext } from '../src/databaseIdentity.js';
if (!globalThis.crypto) globalThis.crypto = webcrypto;
const original = JSON.parse(newDatabaseData());
const other = JSON.parse(newDatabaseData());
assert.notEqual(original.database_id, other.database_id);
original.views = [{id:'v1', name:'Tabla'}, {id:'v2', name:'Tablero'}];
original.columns = [{id:'n', name:'Número', type:'number'}];
const markdown = `:::database\n${JSON.stringify(original)}\n:::`;
const editor = BlockNoteEditor.create({schema, _headless:true});
editor.replaceBlocks(editor.document, mdToBlocks(markdown));
const reloaded = mdToBlocks(blocksToMd(editor.document))[0];
const data = JSON.parse(reloaded.props.data);
assert.equal(data.database_id, original.database_id);
assert.deepEqual(data.views, original.views);
assert.deepEqual(data.columns, original.columns);
const block = {id:'original', type:'database', props:{data:JSON.stringify(original)}, children:[]};
const copy = {...block, id:'copy'};
const checked = duplicateIdentityRepairs([copy, block], new Map([['original', original.database_id]]));
assert.equal(checked.repairs.length, 1);
assert.equal(checked.repairs[0].id, 'copy');
assert.notEqual(JSON.parse(checked.repairs[0].data).database_id, original.database_id);
assert.deepEqual(JSON.parse(checked.repairs[0].data).views, original.views);
assert.equal(duplicateIdentityRepairs([block]).repairs.length, 0);
assert.equal(duplicateIdentityRepairs([{...block, props:{data:'{}'}}]).repairs.length, 0);
const peekEditor = {};
editorDatabaseContext.set(editor, {pageId:'parent'});
editorDatabaseContext.set(peekEditor, {pageId:'row'});
assert.equal(editorDatabaseContext.get(editor).pageId, 'parent');
console.log('ok - persistent sources, independent copies, shared views and editor contexts');

const {TABLE_PREVIEW, isTablePreview, previewNumberValue} = await import('../src/databasePresentation.js');
assert.equal(isTablePreview({}, {type:'table'}), false);
assert.equal(isTablePreview({presentation_preview:TABLE_PREVIEW}, {type:'table'}), true);
assert.equal(isTablePreview({presentation_preview:TABLE_PREVIEW}, {type:'board'}), false);
assert.equal(isTablePreview({presentation_preview:TABLE_PREVIEW}, {type:'gallery'}), false);
assert.equal(previewNumberValue('0'), 0);
assert.equal(previewNumberValue('8.5'), 8.5);
assert.equal(previewNumberValue(''), '');
assert.equal(previewNumberValue('invalid'), '');
assert.equal(previewNumberValue('Infinity'), '');
console.log('ok - table preview is opt-in, excludes boards and preserves numeric zero');
